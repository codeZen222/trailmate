/// 城市名 → 省名（反向索引，首次访问时惰性构建）。
Map<String, String>? _cityToProvince;

Map<String, String> get _c2p {
  if (_cityToProvince == null) {
    final m = <String, String>{};
    kProvinceCities.forEach((prov, cities) {
      for (final c in cities) {
        m[c] = prov;
      }
    });
    _cityToProvince = m;
  }
  return _cityToProvince!;
}

/// 从任意地名文本里识别省份；识别不出返回 null（不猜）。
String? provinceOf(String text) {
  final t = text.trim();
  if (t.isEmpty) return null;

  // 1) 全称/简称别名优先（"内蒙古自治区"要先于"内蒙古"匹配）
  for (final e in _provinceAliases.entries) {
    if (t.startsWith(e.key)) return e.value;
  }
  // 2) 标准省名前缀
  for (final p in kProvinceNames) {
    if (t.startsWith(p)) return p;
  }
  // 3) 文本任意位置包含省名（"洛阳市，河南"）
  for (final p in kProvinceNames) {
    if (t.contains(p)) return p;
  }
  // 4) 反查城市表
  final city = cityOf(t);
  if (city != null) {
    final hit = _c2p[city];
    if (hit != null) return hit;
  }
  return null;
}

/// 直辖市：整体即一个城市，后面跟的区/县不再剥离
const List<String> kMunicipalities = ['北京', '上海', '天津', '重庆'];

/// 生成某省的所有可能前缀写法（全称/简称/民族自治区等）。
List<String> _provinceTokens(String p) {
  return [
    '$p省',
    '$p市',
    '$p自治区',
    '$p特别行政区',
    // 五个自治区的完整民族称谓
    if (p == '内蒙古') '内蒙古自治区',
    if (p == '广西') '广西壮族自治区',
    if (p == '西藏') '西藏自治区',
    if (p == '宁夏') '宁夏回族自治区',
    if (p == '新疆') '新疆维吾尔自治区',
    if (p == '香港') '香港特别行政区',
    if (p == '澳门') '澳门特别行政区',
    p,
  ];
}

/// 按长度降序排列，保证"内蒙古自治区"先于"内蒙古"匹配，
/// 避免残留"古呼和浩特"这类错误。
final List<String> _provincesByLength = [...kProvinceNames]
  ..sort((a, b) => b.length.compareTo(a.length));

/// 自治州短名提取：湘西土家族苗族自治州 → 湘西，大理白族自治州 → 大理。
final RegExp _autonomousPrefecture =
    RegExp(r'^([\u4e00-\u9fa5]{2,6}?)(?:[\u4e00-\u9fa5]*族)+自治州$');

/// 剥离省/市/县/区等行政后缀，取出干净的城市名。
/// 返回 null 表示无法解析（不猜）。
String? cityOf(String text) {
  var t = text.trim();
  if (t.isEmpty) return null;

  // 1) 截断到第一个分隔符（"洛阳，龙门石窟" → 洛阳；"成都-宽窄巷子" → 成都）
  final cut = t.indexOf(RegExp(r'[,，、\-—·/／\s]'));
  if (cut > 0) t = t.substring(0, cut);
  if (t.isEmpty) return null;

  // 2) 直辖市：整体就是它本身，后面的区/县不再剥
  for (final m in kMunicipalities) {
    if (t == m || t.startsWith('$m市') || t.startsWith('$m县')) return m;
  }

  // 3) 自治州：优先用已知短名做最长前缀匹配
  //    （"黔东南苗族侗族自治州" → 黔东南；纯正则会把前缀取成最短的"黔东"）
  if (t.endsWith('自治州')) {
    String? best;
    for (final name in _c2p.keys) {
      if (t.startsWith(name) && (best == null || name.length > best.length)) {
        best = name;
      }
    }
    if (best != null) return best;
    final ap = _autonomousPrefecture.firstMatch(t);
    if (ap != null) return ap.group(1);
  }

  // 4) 剥省级前缀（含全称形式）；剥完为空则说明文本只写了省，按省会处理
  for (final p in _provincesByLength) {
    for (final token in _provinceTokens(p)) {
      if (t.startsWith(token)) {
        final rest = t.substring(token.length).trim();
        if (rest.isEmpty) return _capitalOf(p) ?? p;
        t = rest;
        break;
      }
    }
  }

  // 5) 去行政尾缀（长尾缀在前，避免"自治州"被"州"提前吃掉）
  t = t.replaceAll(
      RegExp(r'(自治州|自治县|自治旗|地区|特别行政区|自治区|新区|市|县|区|盟|旗)$'),
      '');

  // 只剥了一层尾缀时再试一次（"市辖区"这类残留）
  t = t.replaceAll(RegExp(r'^(市|县|区)'), '');

  if (t.isEmpty) return null;
  return t;
}

/// 省名 → 省会城市（文本只写了省时用它兜底）。
String? _capitalOf(String province) {
  final cities = kProvinceCities[province];
  if (cities == null || cities.isEmpty) return null;
  return cities.first;
}
