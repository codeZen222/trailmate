/// 从目的地文本中提取「城市」与「国家」。
///
/// 设计原则：离线、无网络、可预测。优先匹配内置的知名城市词表；
/// 命中不了时退化为「取第一个分隔符前的片段」作为城市名，保证足迹总能点亮。
class CityExtractor {
  /// 返回 (cityName, country)。country 默认 "中国"。
  static ({String city, String country}) extract(String destination) {
    final text = destination.trim();
    if (text.isEmpty) return (city: '未知', country: '中国');

    // 1) 先查海外城市 / 国家（避免"东京"被当成国内）
    for (final entry in _overseasCities.entries) {
      if (text.contains(entry.key)) {
        return (city: entry.key, country: entry.value);
      }
    }

    // 1.5) 【必须早于城市词表】景区/区县先归并到地级市。
    //      「泰山」同时存在于 _cnCities 与归并表，若等到第 3 步才归并，
    //      它会先被当成独立目的地送去查坐标 —— 而实测高德把"泰山"解析到了
    //      台湾南投（全国同名山峰多处），偏差 1300 公里，地图上就会出现
    //      一个不在山东的"泰安"。所以这一步必须在最前面。
    final scope = _matchKnownScope(text);
    if (scope != null) return (city: scope, country: '中国');

    // 2) 再查国内主要城市
    for (final city in _cnCities) {
      if (text.contains(city)) {
        return (city: city, country: '中国');
      }
    }

    // 3) 区县级地名归并到所属地级市。
    //    「济阳」是济南的区，若原样保留会出现：足迹里多出一个不该有的城市、
    //    且离线坐标表查不到它 => 写成 (0,0) 而定位乱飞。用户也明确要求不单独显示。
    final stripped = text.replaceAll(RegExp(r'(新区|县|市|区|旗|州)$'), '');
    for (final e in _districtToCity.entries) {
      if (text.contains(e.key) || stripped == e.key) {
        return (city: e.value, country: '中国');
      }
    }

    // 4) 兜底：按常见分隔符切第一段
    final parts = text.split(RegExp(r'[·\-—\s,，、/]+'));
    final first = parts.firstWhere((p) => p.trim().isNotEmpty, orElse: () => text);
    var name = first.trim();
    // 兜底结果若带行政后缀，去掉更利于与坐标表匹配（"泰安市" -> "泰安"）
    final cut = name.replaceAll(RegExp(r'(新区|市|县|区)$'), '');
    if (cut.length >= 2) name = cut;
    return (city: canonicalCity(name), country: '中国');
  }

  /// 文本是否命中景区/区县归并表（取最长键，避免"泰山风景区"这类漏配）。
  static String? _matchKnownScope(String text) {
    String? best;
    var bestLen = 0;
    for (final map in [_attractionToCity, _districtToCity]) {
      for (final e in map.entries) {
        if (e.key.length > bestLen && text.contains(e.key)) {
          best = e.value;
          bestLen = e.key.length;
        }
      }
    }
    return best;
  }

  /// 把可能含歧义的名字规范成可安全查询的地级市名。
  static String canonicalCity(String name) {
    final n = name.trim();
    if (n.isEmpty) return n;
    // 先查原样，再查剥掉行政/景区后缀的形式
    final direct = _attractionToCity[n] ?? _districtToCity[n];
    if (direct != null) return direct;
    final bare =
        n.replaceAll(RegExp(r'(风景区|景区|旅游区|旅游|市|县|区)$'), '');
    final stripped = _attractionToCity[bare] ?? _districtToCity[bare];
    // 都没命中时返回剥后缀的形式（"泰安市"->"泰安"），比原样更容易被坐标表匹配
    return stripped ?? (bare.length >= 2 ? bare : n);
  }

