  /// 返回 (latitude, longitude)；查不到返回 null。
  static ({double lat, double lon})? lookup(String city) {
    final key = city.replaceAll(RegExp(r'[市县区自治州地区盟旗]$'), '').trim();
    var hit = _coords[city] ?? _coords[key];
    if (hit == null && key.length >= 2) {
      // 模糊匹配必须加约束，否则会定错位：
      // 旧实现是"互为子串即命中 + 取字典序第一个"，实测输入"阳"会命中北京
      // （被"贵阳/洛阳/沈阳"抢先）、"山"会命中普陀山，等于随机定位。
      // 现在要求：① 至少 2 个字；② 只接受"输入包含收录名"这一方向
      // （"河南洛阳"→"洛阳"合理，反过来"阳"⊂"洛阳"不合理）；
      // ③ 多个候选时取最长匹配，最具体的那个才是用户想要的。
      String? best;
      for (final k in _coords.keys) {
        if (k.length < 2) continue;
        if (!key.contains(k)) continue;
        if (best == null || k.length > best.length) best = k;
      }
      if (best != null) hit = _coords[best];
    }
    if (hit == null) return null;
    return (lat: hit[0], lon: hit[1]);
  }

