  /// 按关键词搜索收录地名，返回 (名称, 坐标)。最多 30 条。
  static List<({String name, double lat, double lon})> search(String query) {
    final q = query.trim();
    if (q.isEmpty) return const [];
    final out = <({String name, double lat, double lon})>[];
    for (final e in _coords.entries) {
      if (e.key.contains(q) || q.contains(e.key)) {
        out.add((name: e.key, lat: e.value[0], lon: e.value[1]));
        if (out.length >= 30) break;
      }
    }
    return out;
  }

